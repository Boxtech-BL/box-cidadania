  <h2 id="titulo-consentimento">Consentimento para tratamento de opinião política</h2>
  <p>A sua opinião sobre as proposições é dado pessoal sensível (Lei Geral de Proteção de Dados, art. 5º, II). Para participar das consultas, precisamos do seu consentimento específico:</p>
  <ul>
    <li>o seu voto é guardado separado da sua conta, ligado a ela só por um código que não revela quem você é;</li>
    <li>o seu voto individual nunca é mostrado a ninguém, nem vendido, nem cruzado com outras bases;</li>
    <li>só publicamos resultados somados (país, estado e município), e apenas quando houver ao menos 100 participantes;</li>
    <li>você pode apagar os seus votos, retirar este consentimento ou excluir a conta quando quiser, em Minha conta.</li>
  </ul>
