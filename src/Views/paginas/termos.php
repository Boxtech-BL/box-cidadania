  <h1>Termos de uso</h1>
  <ol>
    <li><strong>O que é.</strong> O Box Cidadania é um aplicativo da BoxTech em que pessoas acompanham proposições em votação na Câmara dos Deputados e no Senado Federal e registram a sua opinião, numa consulta informal.</li>
    <li><strong>Sem valor oficial.</strong> Os resultados mostram só a opinião de quem usa o app. Não são pesquisa de opinião, não têm valor estatístico e não representam a população.</li>
    <li><strong>Neutralidade.</strong> Todos os partidos e parlamentares têm a mesma apresentação, em ordem alfabética, sem destaque editorial. Os resumos descrevem o que muda, sem adjetivos de valor, e passam por revisão humana antes de publicados.</li>
    <li><strong>Conta.</strong> Cada pessoa usa uma única conta, com e-mail confirmado. Um voto por proposição, que pode ser alterado até o início da votação oficial.</li>
    <li><strong>Uso proibido.</strong> Criar contas em massa, automatizar votos ou tentar manipular os resultados leva ao bloqueio das contas envolvidas e à exclusão dos votos.</li>
    <li><strong>Fontes.</strong> Pautas, proposições e votações vêm dos dados abertos da Câmara e do Senado; o texto oficial é sempre o publicado por eles.</li>
    <li><strong>Encerramento.</strong> Você pode excluir a conta quando quiser, em Minha conta.</li>
  </ol>
